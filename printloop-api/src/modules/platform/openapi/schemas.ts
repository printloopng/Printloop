export type Schema = Record<string, any>;

export const str = (extra: Schema = {}): Schema => ({ type: 'string', ...extra });
export const num = (extra: Schema = {}): Schema => ({ type: 'number', ...extra });
export const int = (extra: Schema = {}): Schema => ({ type: 'integer', ...extra });
export const bool = (extra: Schema = {}): Schema => ({ type: 'boolean', ...extra });
export const uuid = (): Schema => ({ type: 'string', format: 'uuid' });
export const date = (): Schema => ({ type: 'string', format: 'date-time' });
export const en = (values: readonly string[]): Schema => ({ type: 'string', enum: [...values] });
export const arr = (items: Schema): Schema => ({ type: 'array', items });
export const ref = (name: string): Schema => ({ $ref: `#/components/schemas/${name}` });
export const nullable = (s: Schema): Schema => ({ anyOf: [s, { type: 'null' }] });
export const anyObj = (): Schema => ({ type: 'object', additionalProperties: true });
export const obj = (properties: Record<string, Schema>, required: string[] = []): Schema => ({
  type: 'object',
  properties,
  ...(required.length ? { required } : {}),
});
export const page = (key: string, item: Schema): Schema =>
  obj({ [key]: arr(item), total: int(), page: int(), limit: int(), totalPages: int() }, [key, 'total']);

